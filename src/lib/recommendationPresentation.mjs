// Both summary and disease APIs must explicitly identify generated text.
export function recommendationPresentation(summary, source, language, fallback = '') {
  const text = typeof summary === 'string' ? summary.trim() : '';
  const isAi = (source === 'ai' || source === 'openai') && Boolean(text);
  const tl = language === 'tl';
  return {
    text: text || fallback,
    isAi,
    header: isAi ? (tl ? 'AI Rekomendasyon' : 'AI Recommendation') : (tl ? 'Rekomendasyon' : 'Recommendation'),
    subtitle: isAi
      ? (tl ? 'Ginawa ng OpenAI batay sa resulta' : 'Generated by OpenAI from the result')
      : (tl ? 'Nakahandang gabay batay sa resulta' : 'Built-in guidance based on the result'),
    insightLabel: isAi ? (tl ? 'Payo ng AI:' : 'AI advice:') : (tl ? 'Gabay:' : 'Guidance:'),
  };
}
